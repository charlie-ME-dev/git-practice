"""
[중간고사 문제 풀이]

Anna는 파티에 친구들을 초대하려고 합니다.
파티 참석 인원(Anna 포함)을 입력 받아,
모든 사람이 최소 1조각씩 먹을 수 있도록 주문해야 할 피자의 최소 개수를
계산하는 Python 코드를 작성하시오.
(단, 피자 1판은 8조각으로 나누어집니다.)
"""

people = int(input("파티 참석 인원: "))
pizzas = (people + 7) // 8
print(f"필요한 피자: {pizzas}판")

